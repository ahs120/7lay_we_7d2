#!/usr/bin/env node
// scripts/copy-ui-assets.mjs
// Copies fonts from @fontsource packages and generates icons.js from lucide-static.
// Run: node scripts/copy-ui-assets.mjs
// Idempotent: second run produces no diff if sources haven't changed.

import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { createHash } from 'crypto';

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dir, '..');
const RENDERER = join(ROOT, 'src', 'renderer');

// ── Helpers ──────────────────────────────────────────────────────────────────

function ensureDir(p) {
  mkdirSync(p, { recursive: true });
}

function hashFile(p) {
  if (!existsSync(p)) return null;
  return createHash('sha256').update(readFileSync(p)).digest('hex');
}

function copyIfChanged(src, dest) {
  const srcHash = createHash('sha256').update(readFileSync(src)).digest('hex');
  const destHash = hashFile(dest);
  if (srcHash === destHash) return false;
  copyFileSync(src, dest);
  return true;
}

function writeIfChanged(dest, content) {
  const newHash = createHash('sha256').update(content).digest('hex');
  const oldHash = hashFile(dest);
  if (newHash === oldHash) return false;
  writeFileSync(dest, content, 'utf8');
  return true;
}

// ── 1. Fonts ──────────────────────────────────────────────────────────────────

const FONTS_DEST = join(RENDERER, 'assets', 'fonts');
ensureDir(FONTS_DEST);

const FONT_PACKAGES = [
  { pkg: '@fontsource/cairo', name: 'cairo' },
  { pkg: '@fontsource/aref-ruqaa', name: 'aref-ruqaa' }
];

// Weights we need
const WANTED_WEIGHTS = [400, 600, 700];
// Subsets we need
const WANTED_SUBSETS = ['arabic', 'latin', 'latin-ext'];

let fontsCopied = 0;
let fontsSkipped = 0;

for (const { pkg, name } of FONT_PACKAGES) {
  const pkgDir = join(ROOT, 'node_modules', pkg, 'files');
  if (!existsSync(pkgDir)) {
    console.error(`ERROR: ${pkg}/files not found`);
    process.exit(1);
  }
  const files = readdirSync(pkgDir);
  for (const file of files) {
    if (!file.endsWith('.woff2')) continue;
    // Filter by weight and subset
    const wantedWeight = WANTED_WEIGHTS.some(w => file.includes(`-${w}-`));
    const wantedSubset = WANTED_SUBSETS.some(s => file.includes(`-${s}-`));
    if (!wantedWeight || !wantedSubset) continue;
    // Also skip display variants
    if (file.includes('display')) continue;
    const src = join(pkgDir, file);
    const dest = join(FONTS_DEST, file);
    if (copyIfChanged(src, dest)) {
      console.log(`  font: copied ${file}`);
      fontsCopied++;
    } else {
      fontsSkipped++;
    }
  }
}
console.log(`Fonts: ${fontsCopied} copied, ${fontsSkipped} up-to-date`);

// ── 2. Font CSS ───────────────────────────────────────────────────────────────

const STYLES_DEST = join(RENDERER, 'styles');
ensureDir(STYLES_DEST);

// Build fonts.css — only local() references, no http
function buildFontFace(family, file, weight, style = 'normal') {
  return `@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url('/assets/fonts/${file}') format('woff2');
}`;
}

const fontFaces = [];

// Cairo (UI font) — arabic, latin, latin-ext
for (const subset of ['arabic', 'latin', 'latin-ext']) {
  for (const weight of [400, 600, 700]) {
    const filename = `cairo-${subset}-${weight}-normal.woff2`;
    if (existsSync(join(FONTS_DEST, filename))) {
      fontFaces.push(buildFontFace('Cairo', filename, weight));
    }
  }
}

// Aref Ruqaa (display/logo font) — arabic, latin, latin-ext
for (const subset of ['arabic', 'latin', 'latin-ext']) {
  for (const weight of [400, 700]) {
    const filename = `aref-ruqaa-${subset}-${weight}-normal.woff2`;
    if (existsSync(join(FONTS_DEST, filename))) {
      fontFaces.push(buildFontFace('Aref Ruqaa', filename, weight));
    }
  }
}

const fontsCss = `/* styles/fonts.css — generated by scripts/copy-ui-assets.mjs — do not edit */
/* No external URLs: all fonts served from app://local/assets/fonts/ */
${fontFaces.join('\n\n')}
`;

const fontsCssPath = join(STYLES_DEST, 'fonts.css');
if (writeIfChanged(fontsCssPath, fontsCss)) {
  console.log('  fonts.css: updated');
} else {
  console.log('  fonts.css: up-to-date');
}

// Verify no http in fonts.css
if (fontsCss.includes('http')) {
  console.error('ERROR: fonts.css contains http — aborting');
  process.exit(1);
}

// ── 3. Icons — generate icons.js from lucide-static ──────────────────────────

const ICONS_DEST = join(RENDERER, 'assets', 'icons');
ensureDir(ICONS_DEST);

const ICONS_WANTED_PATH = join(__dir, 'ui-icons.json');
const LUCIDE_NODES_PATH = join(ROOT, 'node_modules', 'lucide-static', 'icon-nodes.json');
const LUCIDE_SPRITE_PATH = join(ROOT, 'node_modules', 'lucide-static', 'sprite.svg');

if (!existsSync(LUCIDE_NODES_PATH)) {
  console.error('ERROR: lucide-static/icon-nodes.json not found');
  process.exit(1);
}

const wantedNames = JSON.parse(readFileSync(ICONS_WANTED_PATH, 'utf8'));
const allNodes = JSON.parse(readFileSync(LUCIDE_NODES_PATH, 'utf8'));

// Build ICONS map: name → array of [tag, attrs] tuples
const ICONS = {};
const missing = [];

for (const name of wantedNames) {
  if (allNodes[name]) {
    ICONS[name] = allNodes[name];
  } else {
    missing.push(name);
    console.warn(`  WARN: icon "${name}" not found in lucide-static — will use circle-help fallback`);
  }
}

// Always include circle-help as fallback
if (allNodes['circle-help'] && !ICONS['circle-help']) {
  ICONS['circle-help'] = allNodes['circle-help'];
}

// Generate icons.js — no innerHTML, no SVG strings, only node data
const iconsJs = `// assets/icons/icons.js — generated by scripts/copy-ui-assets.mjs — do not edit
// No SVG strings, no innerHTML. Data is used by components/icon.js via createElementNS.
// No external URLs.

export const ICONS = Object.freeze(${JSON.stringify(ICONS, null, 2)});

export const ICON_NAMES = Object.freeze(${JSON.stringify(Object.keys(ICONS))});
`;

const iconsJsPath = join(ICONS_DEST, 'icons.js');
if (writeIfChanged(iconsJsPath, iconsJs)) {
  console.log(`  icons.js: updated (${Object.keys(ICONS).length} icons, ${missing.length} missing)`);
} else {
  console.log(`  icons.js: up-to-date (${Object.keys(ICONS).length} icons)`);
}

// Verify no http in icons.js
if (iconsJs.includes('http://') && !iconsJs.includes('http://www.w3.org')) {
  console.error('ERROR: icons.js contains http — aborting');
  process.exit(1);
}

// ── 4. Copy SVG files ─────────────────────────────────────────────────────────

const SVG_DEST = join(ICONS_DEST, 'svg');
ensureDir(SVG_DEST);

// Copy individual SVG files from lucide-static if they exist
// lucide-static doesn't ship individual SVGs in this version, so we generate them
// from the node data for reference/debugging
let svgCopied = 0;

const SVG_NS = 'http://www.w3.org/2000/svg';

for (const [name, nodes] of Object.entries(ICONS)) {
  const destSvg = join(SVG_DEST, `${name}.svg`);
  // Build a minimal SVG string for reference (not used at runtime)
  const childElements = nodes.map(([tag, attrs]) => {
    const attrStr = Object.entries(attrs)
      .map(([k, v]) => `${k}="${v}"`)
      .join(' ');
    return `  <${tag} ${attrStr}/>`;
  }).join('\n');

  const svgContent = `<svg xmlns="${SVG_NS}" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
${childElements}
</svg>
`;
  if (writeIfChanged(destSvg, svgContent)) {
    svgCopied++;
  }
}

console.log(`SVGs: ${svgCopied} updated, ${Object.keys(ICONS).length - svgCopied} up-to-date`);

// ── 5. Islamic tile SVG ───────────────────────────────────────────────────────

const PATTERNS_DEST = join(RENDERER, 'assets', 'patterns');
ensureDir(PATTERNS_DEST);

// Eight-point star pattern — 120×120, stroke #B8955E (gold token)
// Built as a tiling SVG pattern element
const islamicTileSvg = `<svg xmlns="${SVG_NS}" width="120" height="120" viewBox="0 0 120 120">
  <!-- Eight-point star Islamic tile pattern -->
  <!-- Stroke color matches --gold token: #B8955E -->
  <defs>
    <pattern id="tile" x="0" y="0" width="60" height="60" patternUnits="userSpaceOnUse">
      <!-- Outer octagon -->
      <polygon
        points="22,8 38,8 52,22 52,38 38,52 22,52 8,38 8,22"
        fill="none"
        stroke="#B8955E"
        stroke-width="1.5"
      />
      <!-- Inner star diagonals -->
      <line x1="8" y1="22" x2="52" y2="38" stroke="#B8955E" stroke-width="0.75" opacity="0.5"/>
      <line x1="8" y1="38" x2="52" y2="22" stroke="#B8955E" stroke-width="0.75" opacity="0.5"/>
      <line x1="22" y1="8" x2="38" y2="52" stroke="#B8955E" stroke-width="0.75" opacity="0.5"/>
      <line x1="38" y1="8" x2="22" y2="52" stroke="#B8955E" stroke-width="0.75" opacity="0.5"/>
      <!-- Center dot -->
      <circle cx="30" cy="30" r="2" fill="#B8955E" opacity="0.4"/>
    </pattern>
  </defs>
  <rect width="120" height="120" fill="url(#tile)"/>
</svg>
`;

const islamicTilePath = join(PATTERNS_DEST, 'islamic-tile.svg');
if (writeIfChanged(islamicTilePath, islamicTileSvg)) {
  console.log('  islamic-tile.svg: updated');
} else {
  console.log('  islamic-tile.svg: up-to-date');
}

// ── Summary ───────────────────────────────────────────────────────────────────

console.log('\nassets:ui done ✅');
